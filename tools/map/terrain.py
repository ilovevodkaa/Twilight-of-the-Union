_PREP = {k: [prep(Polygon(p)) for p in v] for k, v in ZONES.items()}


def _in(kind, lon, lat):
    pt = Point(lon, lat)
    return any(p.contains(pt) for p in _PREP[kind])


def _noise(lon, lat):
    return (np.sin(lon * 0.83 + 1.7) * np.sin(lat * 1.07 + 0.4) + 0.5 * np.sin(lon * 0.37 - lat * 0.53 + 2.0))


def classify(w, rast, dem, places):
    """Returns array of terrain names per province id (None for index 0)."""
    P, N, kind = w["P"], w["N"], w["kind"]
    C = rast["C"]
    elev = np.where(C == 0, np.maximum(dem, 0), 0).astype(np.float64)
    cnt = np.bincount(P.ravel(), minlength=N + 1).astype(np.float64)
    s1 = np.bincount(P.ravel(), elev.ravel(), N + 1)
    s2 = np.bincount(P.ravel(), (elev ** 2).ravel(), N + 1)
    mean = s1 / np.maximum(cnt, 1)
    std = np.sqrt(np.maximum(s2 / np.maximum(cnt, 1) - mean ** 2, 0))
    # biggest city per province
    big = np.zeros(N + 1)
    for pl in places:
        big[pl["prov"]] = max(big[pl["prov"]], pl["pop"])
    out = [None] * (N + 1)
    for i in range(1, N + 1):
        if kind[i] == "sea":
            out[i] = "ocean"
        elif kind[i] == "lake":
            out[i] = "lakes"
        else:
            lon, lat = geo.px_to_lonlat(w["cx"][i], w["cy"][i])
            lon, lat = float(lon), float(lat)
            m, s = mean[i], std[i]
            if big[i] >= 900000:
                t = "urban"
            elif m >= 2000 or (m >= 1300 and s >= 300) or s >= 420:
                t = "mountain"
            elif (m >= 650 and s >= 100) or s >= 190 or m >= 1300:
                t = "hills"
            elif _in("marsh", lon, lat):
                t = "marsh"
            elif _in("desert", lon, lat):
                t = "desert"
            elif _in("jungle", lon, lat):
                t = "jungle"
            elif _in("forest", lon, lat) and _noise(lon, lat) > -0.55:
                t = "forest"
            else:
                t = "plains"
            out[i] = t
    return out, mean, std
