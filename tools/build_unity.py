def build_preview(name, scale, ddr, ger, lang, status, flags, loc):
    code = "ru" if lang == "russian" else "en"
    lv = dict(loc[code])
    share = share_ddr(ddr, ger)
    vals = {"TOTU_un_scale": scale, "TOTU_un_ddr": ddr, "TOTU_un_ger": ger, "TOTU_un_share_ddr": share,
            "TOTU_un_share_ger": 100 - share}

    def fill(key):
        return re.sub(r"\[\?(\w+)\|0\]", lambda m: str(vals[m.group(1)]), lv[key])

    out = ROOT / f"tools/data/{name}_render.png"
    cmd = [sys.executable, str(ROOT / "tools/render_gui.py"), "TOTU_unity_window", "--file", "interface/totu_unity.gui",
           "--res", f"{WIN_W}x{WIN_H}", "--bg", "none", "--no-placeholders", "--out", str(out), "--lang", lang,
           "--text", f"unity_status={fill(status)}", "--text", f"scale_value={fill('TOTU_un_scale_value')}",
           "--text", f"side_ddr={fill('TOTU_un_side_ddr')}", "--text", f"side_ger={fill('TOTU_un_side_ger')}",
           "--text", "mark_2p4=" + lv["TOTU_un_2p4_consent" if "consent" in flags else
                                      "TOTU_un_2p4_veto" if "veto" in flags else "TOTU_un_2p4_plain"],
           "--text", f"mark_ref={lv['TOTU_un_ref_plain']}"]
    if "frozen" not in flags:
        cmd += ["--hide", "frozen_overlay"]
    cells = scale_cells(scale)
    tc = tug_cells(share)
    for i in range(1, SEGS + 1):
        cmd += ["--state", f"frame:bar_{i}={seg_frame(cells, i)}", "--state", f"frame:tug_{i}={seg_frame(tc, i)}"]
    cmd += ["--prop", f"tug_knot.position.x={KNOT_X0 + TCELL * tc}"]
    res = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    issues = [ln for ln in (res.stdout + res.stderr).splitlines()
              if any(w in ln for w in ("WARN", "Error", "Traceback", " CUT", "GROWS", "OVERFLOWS"))]
    for line in issues:
        tb._say(f"  render_gui ({name}):", line.strip())
    if res.returncode != 0 or not out.exists():
        tb._say("preview failed:", name, res.stderr[-800:])
        return
    win = Image.open(out).convert("RGBA")
    rng = np.random.default_rng(1990)
    pad = 16
    bg = np.full((WIN_H + 2 * pad, WIN_W + 2 * pad, 3), PANEL, np.float64)
    bg += rng.normal(0, 2.2, bg.shape)
    panel = Image.fromarray(bg.clip(0, 255).astype(np.uint8), "RGB").convert("RGBA")
    panel.alpha_composite(win, (pad, pad))
    PREVIEW.mkdir(parents=True, exist_ok=True)
    panel.convert("RGB").save(PREVIEW / f"{name}.png")
    out.unlink()
    tb._say(f"wrote tools/preview/{name}.png (scale {scale}, share {share}/{100 - share})")


def icon_sheet(groups, path):
    pad, gap = 16, 14
    width = pad + max(sum(ic.width * 3 + gap for ic in icons) for icons in groups) + pad
    height = pad + sum(max(ic.height for ic in icons) * 4 + 3 * gap for icons in groups) + pad
    img = Image.new("RGBA", (width, height), PANEL + (255,))
    y = pad
    for icons in groups:
        h = max(ic.height for ic in icons)
        x = pad
        for ic in icons:
            img.alpha_composite(ic.resize((ic.width * 3, ic.height * 3), Image.NEAREST), (x, y))
            img.alpha_composite(ic, (x, y + h * 3 + gap))
            x += ic.width * 3 + gap
        y += h * 4 + 3 * gap
    img.convert("RGB").save(path)
    tb._say("wrote", tb.rel(path))


