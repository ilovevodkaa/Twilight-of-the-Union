def build_cat_picture():
    """114x101 like the vanilla category pictures: the gate, faded warm photo, dark vignette, rounded dark frame."""
    w, h = CAT_PIC
    im = photo("totu_unity_gate")
    W, H = im.size
    box_w = round(W * 0.50)
    box_h = round(box_w * h / w)
    x0 = round(W * 0.17)
    y0 = round(H * 0.04)
    im = im.crop((x0, y0, x0 + box_w, y0 + box_h)).resize((w, h), Image.LANCZOS)
    a = np.asarray(im, np.float64)
    g = a.mean(2, keepdims=True)
    a = g + (a - g) * 0.45
    a = a * np.array((1.04, 0.98, 0.88))
    a = (a - 128) * 1.08 + 124
    x, y = grid(w, h, 1)
    v = np.hypot((x - w / 2) / (w / 2), (y - h / 2) / (h / 2))
    a = a * (1 - 0.35 * np.clip(v - 0.55, 0, 1) ** 1.4)[:, :, None]
    r = 4
    cx = np.clip(x, r, w - r)
    cy = np.clip(y, r, h - r)
    dist = r - np.hypot(x - cx, y - cy)
    alpha = np.clip(dist + 0.5, 0, 1)
    frame = np.clip(1.5 - dist, 0, 1)
    a = a * (1 - frame[:, :, None]) + np.array((22, 19, 17)) * frame[:, :, None]
    return to_img(a, alpha)


