def knot():
    """The knot of the rope: a cream capsule with a dark rim, a shaded right side and four diagonal twists."""
    w, h = KNOT_W, KNOT_H
    x, y = grid(w, h)
    cx, r = w / 2, 3.6
    yy = np.clip(y, 1.2 + r, h - 1.2 - r)
    d = np.hypot(x - cx, y - yy)
    rim = np.clip(r + 1.2 - d + 0.5, 0, 1)
    body = np.clip(r - d + 0.5, 0, 1)
    c = canvas(w * SS, h * SS)
    c = layer(c, (10, 8, 6), rim * 0.92)
    c = layer(c, (232, 218, 186), body)
    c = layer(c, (150, 128, 96), body * np.clip((x - cx) / r, 0, 1) * 0.45)
    for k in range(4):
        ty = h / 2 - 7.5 + k * 5
        band = np.clip(0.75 - np.abs((y - ty) - 0.6 * (x - cx)), 0, 1) * body
        c = layer(c, (118, 94, 62), band * 0.9)
    return down(finish(c), w, h)


def flag_img(path, w=FLAG_W, h=FLAG_H):
    """A flag from a vanilla .tga (82x52) at w x h: 1 px dark frame, the flag inside."""
    fl = Image.open(path).convert("RGBA").resize((w - 2, h - 2), Image.LANCZOS)
    out = Image.new("RGBA", (w, h), (14, 12, 11, 255))
    out.alpha_composite(fl, (1, 1))
    a = np.asarray(out, np.float64)
    a[1:2, 1:-1, :3] = a[1:2, 1:-1, :3] * 0.75 + 255 * 0.25 * 0.4   # a faint top light
    return Image.fromarray(a.clip(0, 255).astype(np.uint8), "RGBA")


def tricolour_disc(c, x, y, cx, cy, R, ring=1.6, inner_shadow=True):
    """Black-red-gold in a disc with a gold ring (the colours both German states share)."""
    d = np.hypot(x - cx, y - cy)
    c = layer(c, (6, 5, 4), np.clip(R + 1.4 - d + 0.5, 0, 1) * 0.75)
    c = layer(c, mix(GOLD, (0, 0, 0), 0.05), np.clip(R - d + 0.5, 0, 1))
    disc = np.clip(R - ring - d + 0.5, 0, 1)
    top = cy - (R - ring)
    third = 2 * (R - ring) / 3
    for k, col in enumerate(((26, 24, 22), (176, 40, 32), (222, 176, 48))):
        band = disc * (y >= top + k * third) * (y < top + (k + 1) * third + (0 if k < 2 else 2))
        c = layer(c, col, band)
    if inner_shadow:
        c = layer(c, (0, 0, 0), disc * np.clip((d - (R - ring - 4)) / 4, 0, 1) * 0.35)
    return c


