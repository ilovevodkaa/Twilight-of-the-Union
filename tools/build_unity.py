def scale_segment_strip():
    """6 frames of SEG_W x BAR_H: frame f has f of its 5 cells filled with gold, the rest are dark wells."""
    px = np.zeros((BAR_H, SEG_W * 6, 4), np.float64)
    for f in range(6):
        for c in range(SEG_CELLS):
            x0 = f * SEG_W + c * CELL
            x1 = x0 + CELL - 1
            if c < f:
                for y in range(2, BAR_H - 2):
                    t = (y - 2) / (BAR_H - 5)
                    px[y, x0:x1] = mix(mix(FILL, (255, 255, 255), 0.18), mix(FILL, (0, 0, 0), 0.32), t) + (255,)
                px[2, x0:x1, :3] = mix(FILL, (255, 255, 255), 0.4)
            else:
                px[2:BAR_H - 2, x0:x1] = (18, 16, 14, 200)
                edge = (62, 55, 48, 255)
                px[2, x0:x1] = edge
                px[BAR_H - 3, x0:x1] = edge
                px[2:BAR_H - 2, x0] = edge
                px[2:BAR_H - 2, x1 - 1] = edge
    return Image.fromarray(px.clip(0, 255).astype(np.uint8), "RGBA")


def tug_segment_strip():
    """6 frames of TSEG_W x BAR_H: frame f has its first f cells in the GDR red, the rest in the FRG blue."""
    px = np.zeros((BAR_H, TSEG_W * 6, 4), np.float64)
    for f in range(6):
        for c in range(SEG_CELLS):
            x0 = f * TSEG_W + c * TCELL
            x1 = x0 + TCELL - 1
            col = EAST if c < f else WEST
            for y in range(2, BAR_H - 2):
                t = (y - 2) / (BAR_H - 5)
                px[y, x0:x1] = mix(mix(col, (255, 255, 255), 0.12), mix(col, (0, 0, 0), 0.35), t) + (255,)
            px[2, x0:x1, :3] = mix(col, (255, 255, 255), 0.35)
    return Image.fromarray(px.clip(0, 255).astype(np.uint8), "RGBA")


def scale_marks():
    """Overlay of the scale bar (BAR_W + 2 x BAR_H + MARKS_H): the gold referendum line at the 100 % end and small
    gold pointers under the bar at 50 %, 75 % (2+4) and 100 %."""
    w, h = BAR_W + 2, BAR_H + MARKS_H
    x, y = grid(w, h)
    c = canvas(w * SS, h * SS)
    end = BAR_W - 1                                            # the gap column after the last cell
    c = layer(c, GOLD, poly_mask(w, h, [(end, 0), (end + 2, 0), (end + 2, BAR_H + 1), (end, BAR_H + 1)]) * 0.95)
    for pct in (50, MARK_2P4, MARK_REF):
        cx = BAR_W * pct / 100 - 0.5 if pct < 100 else end + 1
        tri = poly_mask(w, h, [(cx, BAR_H + 1), (cx + 3.2, BAR_H + 5.5), (cx - 3.2, BAR_H + 5.5)])
        c = layer(c, (8, 6, 5), shadow(tri.astype(np.float64), 1, 0.4, 0.6))
        c = layer(c, GOLD if pct != 50 else mix(GOLD, (120, 110, 100), 0.4), tri)
    return down(finish(c), w, h)


