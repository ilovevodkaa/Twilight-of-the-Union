def build_header():
    """500x52 band of the Brandenburg Gate photo (the entablature and the lit column tops) in a dark gold duotone,
    darker on the left under the title."""
    im = photo("totu_unity_gate")
    W, H = im.size
    x0, x1 = round(W * 0.098), round(W * 0.75)
    band_h = round((x1 - x0) * HEADER_H / WIN_W)
    top = round(H * 0.28)
    im = im.crop((x0, top, x1, top + band_h)).resize((WIN_W, HEADER_H), Image.LANCZOS)
    L = np.asarray(im.convert("L"), np.float64) / 255
    lo, hi = np.percentile(L, 3), np.percentile(L, 97)
    L = np.clip((L - lo) / max(1e-6, hi - lo), 0, 1) ** 0.9
    dark, light = np.array((14, 11, 9)), np.array((190, 154, 96))
    rgb = dark + (light - dark) * L[:, :, None]
    xx = np.linspace(0, 1, WIN_W)[None, :]
    rgb = rgb * (0.38 + 0.52 * np.clip((xx - 0.05) / 0.75, 0, 1) ** 1.2)[:, :, None]
    yy = np.linspace(0, 1, HEADER_H)[:, None]
    rgb = rgb * (1 - 0.25 * yy[:, :, None] ** 2)
    rgb[0, :] = (10, 8, 7)
    rgb[-1, :] = mix(GOLD, (20, 16, 14), 0.35)
    rgb[-2, :] = rgb[-2, :] * 0.6
    return to_img(rgb, np.ones((HEADER_H, WIN_W)))


