def doc_names():
    docs = GAME / "documentation"
    names = set()
    for f in ("effects_documentation.md", "triggers_documentation.md"):
        names |= set(re.findall(r"^## (\w+)", (docs / f).read_text(encoding="utf-8", errors="replace"), re.M))
    mods = set(re.findall(r"^## (\w+)", (docs / "modifiers_documentation.md").read_text(encoding="utf-8",
                                                                                     errors="replace"), re.M))
    return names, mods


def strip_script(text):
    t = re.sub(r"#.*", "", text)
    return re.sub(r'"[^"\n]*"', '""', t)


def braces_ok(text):
    depth = 0
    for ch in strip_script(text):
        depth += ch == "{"
        depth -= ch == "}"
        if depth < 0:
            return False
    return depth == 0


def defined_blocks(text):
    return set(re.findall(r"^(\w+)\s*=\s*\{", strip_script(text), re.M))


def check_all(files, loc):
    probs = []
    for path, text in files.items():
        if path.suffix in (".txt", ".gui", ".gfx") and not braces_ok(text):
            probs.append(f"{path.name}: braces do not balance")
    by = {p.name: t for p, t in files.items()}
    api, logic, trig = by["TOTU_unity_api.txt"], by["TOTU_unity_effects.txt"], by["TOTU_unity_triggers.txt"]
    my_effects = defined_blocks(api) | defined_blocks(logic)
    my_triggers = defined_blocks(trig)
    # the API the focus trees call
    need_e = {f"TOTU_unity_{s}_pull_{n}" for s in ("ddr", "ger") for n in AMOUNTS}
    need_e |= {f"TOTU_unity_progress_{o}_{n}" for o in ("add", "sub") for n in AMOUNTS}
    need_e |= {f"TOTU_unity_freeze_{d}" for d in FREEZES} | {"TOTU_unity_unfreeze", "TOTU_unity_end_talks"}
    need_t = {"TOTU_unity_active", "TOTU_unity_ddr_leads", "TOTU_unity_ger_leads"}
    probs += [f"API effect missing: {n}" for n in sorted(need_e - my_effects)]
    probs += [f"API trigger missing: {n}" for n in sorted(need_t - my_triggers)]
    # every key = in the script is a structural word, a documented effect/trigger, a scripted effect/trigger of the mod,
    # a modifier, a variable (TOTU_/un_/ung_/global.), or a block defined here
    docs, mods = doc_names()
    mod_effects = set()
    for f in (ROOT / "common/scripted_effects").glob("*.txt"):
        if f.name not in ("TOTU_unity_api.txt", "TOTU_unity_effects.txt"):
            mod_effects |= defined_blocks(f.read_text(encoding="utf-8-sig", errors="replace"))
    known = STRUCTURAL | docs | mods | my_effects | my_triggers | mod_effects | {"DDR", "GER", "SOV", "ROOT"}
    known |= {d["id"] for d in DECISIONS} | {"TOTU_unity_category"} | {i[0] for i in IDEAS}
    known |= {m[0] for m in OPINION_MODIFIERS}
    for path, text in files.items():
        if path.suffix != ".txt" or "scripted_guis" in path.as_posix():
            continue
        for key in re.findall(r"([\w.@]+)\s*=", strip_script(text)):
            if key in known or re.match(r"(TOTU_un_|un_|ung_|global\.)", key):
                continue
            probs.append(f"{path.name}: unknown key {key}")
    for name in ("TOTU_bloc_leave",):
        if name not in mod_effects:
            probs.append(f"scripted effect {name} not found in the mod")
    # sprites: declared here or elsewhere, textures made
    declared = {n for n, _, _ in all_sprites()}
    elsewhere = set(tb.existing_names("*.gfx", exclude=[ROOT / "interface/totu_unity.gfx"]))
    used = set()
    for path, text in files.items():
        used |= set(re.findall(r"\b(GFX_\w+)", strip_script(text) if path.suffix != ".gfx" else ""))
    for s in sorted(used):
        if s not in declared and s not in elsewhere:
            probs.append(f"sprite {s} is not declared")
    for s in sorted(declared & elsewhere):
        probs.append(f"sprite {s} is also declared elsewhere: {tb.existing_names('*.gfx')[s]}")
    for iid, *_ in IDEAS:
        if f"GFX_idea_{iid.lower()}" not in declared:
            probs.append(f"idea {iid}: picture sprite missing")
    # localisation: every key the files use exists in both languages
    keys = {"ru": {k for k, _ in loc["ru"]}, "en": {k for k, _ in loc["en"]}}
    for code in ("ru", "en"):
        if len(keys[code]) != len(loc[code]):
            probs.append(f"duplicate loc keys in {code}")
    used_keys = set()
    for path, text in files.items():
        t = strip_script(text) if path.suffix != ".gui" else text
        used_keys |= set(re.findall(r"\b(?:tooltip|custom_effect_tooltip|localization_key|title|desc|name|text|"
                                    r"pdx_tooltip)\s*=\s*\"?([A-Za-z_][\w.]*)\"?", t))
        if path.suffix == ".gui":
            used_keys |= set(re.findall(r'text = "([^"]+)"', text))
    used_keys |= {d["id"] for d in DECISIONS} | {d["id"] + "_desc" for d in DECISIONS}
    used_keys |= {i[0] for i in IDEAS} | {i[0] + "_desc" for i in IDEAS} | {m[0] for m in OPINION_MODIFIERS}
    used_keys |= {"TOTU_unity_category", "TOTU_unity_category_desc"}
    for t in COSMETIC_FLAGS:
        used_keys |= {t, f"{t}_DEF", f"{t}_ADJ"} | {f"{t}_{g}{s}" for g in IDEOLOGY_GROUPS for s in ("", "_DEF", "_ADJ")}
    not_loc = {"TOTU_unity_window", "TOTU_unity_gui", "TOTU_un_status", "TOTU_un_2p4", "TOTU_un_ref"}
    not_loc |= {n for n in used_keys if n.startswith(("section_", "rule_", "bar_", "tug_", "flag_", "mark_", "side_",
                                                       "scale_", "status_", "unity_", "frozen_", "header", "emblem"))}
    not_loc |= set(re.findall(r'name = "(\w+)"', files[ROOT / "interface/totu_unity.gui"]))
    for k in sorted(used_keys - not_loc):
        for code in ("ru", "en"):
            if k not in keys[code]:
                probs.append(f"loc key {k} missing in {code}")
    # every [defined_text] and [?var] in the loc is one we provide
    texts = " ".join(v for _, v in loc["ru"] + loc["en"])
    for ref in set(re.findall(r"\[(\w+)\]", texts)):
        if ref not in ("TOTU_un_status", "TOTU_un_2p4", "TOTU_un_ref"):
            probs.append(f"loc uses unknown scripted loc [{ref}]")
    for var in set(re.findall(r"\[\?(\w+)", texts)):
        if var not in ("TOTU_un_scale", "TOTU_un_ddr", "TOTU_un_ger", "TOTU_un_share_ddr", "TOTU_un_share_ger"):
            probs.append(f"loc uses unknown variable {var}")
    for k, v in loc["ru"] + loc["en"]:
        if '"' in v:
            probs.append(f"straight double quote in {k}")
    return probs


